"""Write ``report/generated/numbers.tex`` so the LaTeX report fills itself from real results."""
from __future__ import annotations

import json
import statistics
from collections import Counter
from pathlib import PurePosixPath
from typing import Any

from . import config
from .utils import PipelineError, get_logger, read_jsonl

logger = get_logger(__name__)

_TEX_SPECIAL = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}


def tex_escape(value: object) -> str:
    """Escape LaTeX special characters (notably underscores)."""
    return "".join(_TEX_SPECIAL.get(c, c) for c in str(value))


def _latest_by_source(log: list[dict[str, Any]]) -> dict[tuple[str, str], dict[str, Any]]:
    latest: dict[tuple[str, str], dict[str, Any]] = {}
    for entry in log:
        latest[(entry["kind"], entry["source"])] = entry
    return latest


def _split(counter: Counter) -> str:
    return ", ".join(f"{k}: {v}" for k, v in sorted(counter.items(), key=lambda kv: (-kv[1], kv[0])))


def compute_numbers(
    log: list[dict[str, Any]], audit: dict[str, int], records: list[dict[str, Any]]
) -> dict[str, str]:
    """Compute every report key from the log, audit and clean records."""
    latest = _latest_by_source(log)
    web = [e for (kind, _), e in latest.items() if kind == "web"]
    files_ok = [e for (kind, _), e in latest.items() if kind == "file" and e["success"]]
    ext = Counter(PurePosixPath(e["source"]).suffix.lower() for e in files_ok)
    dates = sorted(e["ts"][:10] for e in log)
    date_range = dates[0] if dates[0] == dates[-1] else f"{dates[0]} to {dates[-1]}"
    words = [r["word_count"] for r in records]
    median = statistics.median(words) if words else 0
    return {
        "date_range": date_range,
        "urls_attempted": str(len(web)),
        "urls_ok": str(sum(1 for e in web if e["success"])),
        "f_pdf": str(ext[".pdf"]),
        "f_docx": str(ext[".docx"]),
        "f_txt": str(ext[".txt"]),
        "failed": str(sum(1 for e in latest.values() if not e["success"])),
        "raw": str(audit["raw"]),
        "rej_missing": str(audit["rejected_missing"]),
        "imputed": str(audit["imputed_title"] + audit["imputed_language"]),
        "dups": str(audit["removed_duplicates"]),
        "short": str(audit["excluded_short"]),
        "outliers": str(audit["flagged_outliers"]),
        "final": str(audit["final"]),
        "min_words": str(config.MIN_WORDS),
        "median_words": f"{median:g}" if isinstance(median, float) else str(median),
        "type_split": _split(Counter(r["source_type"] for r in records)),
        "lang_split": _split(Counter(r["language"] for r in records)),
    }


def run() -> dict[str, str]:
    """Read pipeline outputs and write numbers.tex."""
    log = read_jsonl(config.COLLECTION_LOG)
    if not log:
        raise PipelineError(f"Collection log missing or empty: {config.COLLECTION_LOG}")
    if not config.AUDIT_JSON.exists():
        raise PipelineError(f"Cleaning audit missing: {config.AUDIT_JSON}. Run cleaning first.")
    records = read_jsonl(config.CLEAN_RECORDS)
    if not records:
        raise PipelineError(f"No cleaned records at {config.CLEAN_RECORDS}.")
    audit = json.loads(config.AUDIT_JSON.read_text(encoding="utf-8"))
    numbers = compute_numbers(log, audit, records)
    lines = ["% Auto-generated by data_scripts/make_report_numbers.py. Do not edit."]
    for key, value in numbers.items():
        lines.append(f"\\expandafter\\def\\csname val@{key}\\endcsname{{{tex_escape(value)}}}")
    config.NUMBERS_TEX.parent.mkdir(parents=True, exist_ok=True)
    config.NUMBERS_TEX.write_text("\n".join(lines) + "\n", encoding="utf-8")
    logger.info("wrote %s", config.NUMBERS_TEX)
    return numbers


if __name__ == "__main__":
    run()
